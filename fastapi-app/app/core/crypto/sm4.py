_MASK = 0xFFFFFFFF


def _rotl(x: int, n: int) -> int:
    return ((x << n) | (x >> (32 - n))) & _MASK


def _tau(a: int) -> int:
    return ((_SBOX[(a >> 24) & 0xFF] << 24)
            | (_SBOX[(a >> 16) & 0xFF] << 16)
            | (_SBOX[(a >> 8) & 0xFF] << 8)
            | _SBOX[a & 0xFF])


def _t_key(x: int) -> int:
    return _tau(x) ^ _rotl(_tau(x), 13) ^ _rotl(_tau(x), 23)


def _t_enc(x: int) -> int:
    return _tau(x) ^ _rotl(_tau(x), 2) ^ _rotl(_tau(x), 10) ^ _rotl(_tau(x), 18) ^ _rotl(_tau(x), 24)


def _expand_key(key: bytes) -> list[int]:
    mk = [int.from_bytes(key[i * 4:i * 4 + 4], "big") for i in range(4)]
    k = [mk[i] ^ _FK[i] for i in range(4)]
    rk = []
    for i in range(32):
        # 轮密钥递推用最近四个字: rk_i = K_i ⊕ T'(K_{i+1} ⊕ K_{i+2} ⊕ K_{i+3} ⊕ CK_i)
        v = k[i + 1] ^ k[i + 2] ^ k[i + 3] ^ _CK[i]
        nk = k[i] ^ _t_key(v)
        rk.append(nk)
        k.append(nk)
    return rk


def _crypt_block(rk: list[int], block: bytes, decrypt: bool = False) -> bytes:
    keys = rk if not decrypt else list(reversed(rk))
    x = [int.from_bytes(block[i * 4:i * 4 + 4], "big") for i in range(4)]
    for i in range(32):
        # 轮变换同样用最近四个字: X_{i+4} = X_i ⊕ T(X_{i+1} ⊕ X_{i+2} ⊕ X_{i+3} ⊕ rk_i)
        tmp = x[i + 1] ^ x[i + 2] ^ x[i + 3] ^ keys[i]
        x.append(x[i] ^ _t_enc(tmp))
    out = x[35], x[34], x[33], x[32]
    return b"".join(v.to_bytes(4, "big") for v in out)


def _xor(a: bytes, b: bytes) -> bytes:
    return bytes(x ^ y for x, y in zip(a, b))


def sm4_ctr(cipher: bytes, key: bytes, iv: bytes | None = None) -> bytes:
    """SM4-CTR 模式加解密（对称）。cipher 为任意长度密文，输出明文；加密时传明文同理。"""
    if len(key) != 16:
        raise ValueError("SM4 key 必须为 16 字节")
    iv = iv or b"\x00" * 16
    rk = _expand_key(key)
    out = bytearray()
    counter = int.from_bytes(iv, "big")
    for i in range(0, len(cipher), 16):
        ctr_block = (counter + (i // 16)).to_bytes(16, "big")
        keystream = _crypt_block(rk, ctr_block)
        out += _xor(cipher[i:i + 16], keystream)
    return bytes(out)


def _strip_pkcs7(data: bytes) -> bytes:
    """Java 侧算法串为 SM4/CTR/PKCS5Padding，BouncyCastle 在 CTR 下仍施加 PKCS5 填充，需剥除。"""
    if data:
        pad = data[-1]
        if 1 <= pad <= 16 and data[-pad:] == bytes([pad]) * pad:
            return data[:-pad]
    return data


def decrypt_enc_value(enc_text: str, key: str = "Q1w2e3r4t5y6u7i8") -> str:
    """解密原 Java 配置文件中的 Enc[xxx] 形态密文，返回明文。

    对齐 SM4Utils.decryptByBase64: SM4/CTR/PKCS5Padding、密钥取 UTF-8 字节、IV=16 零字节、Base64 输入。
    """
    if enc_text.startswith("Enc[") and enc_text.endswith("]"):
        enc_text = enc_text[4:-1]
    plain = sm4_ctr(base64.b64decode(enc_text), key.encode("utf-8"))
    return _strip_pkcs7(plain).decode("utf-8")
